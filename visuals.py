def clear_screen():
    os.system('cls' if os.name == 'nt' else 'clear')


def print_separator():
    print("-" * 50)


# ГЕНЕРАТОР ОБРАЗ (ТОКСИЧНІСТЬ)
def get_insult(is_correct):
    correct_phrases = [
        "Ого, пощастило.",
        "Не зазнавайся, це було легко.",
        "Ну нарешті ти ввімкнув мозок.",
        "Дивно, я думав ти помилишся.",
        "Вау, ти вмієш читати!"
    ]
    incorrect_phrases = [
        "Серйозно? Моя мікрохвильовка розумніша.",
        "Ганьба роду людському.",
        "Ти точно вчився в школі?",
        "Видаліть цей застосунок, вам вже нічого не допоможе.",
        "Це було елементарно, Ватсон... але не для тебе.",
        "Рука-обличчя."
    ]
    return random.choice(correct_phrases) if is_correct else random.choice(incorrect_phrases)


def show_main_menu():
    while True:
        clear_screen()
        print_separator()
        print("       === ТОКСИЧНИЙ КВІЗ: ОБЕРИ ПРЕДМЕТ ===")
        print_separator()

        for key, data in MENU_STRUCTURE.items():
            print(f" [{key}] {data['name']}")

        print("\n [0] Вихід (втекти з ганьбою)")
        print_separator()

        choice = input(" Твій вибір >>> ")

        if choice == "0":
            print("\nСлабкі духом нам не потрібні. Бувай.")
            sys.exit()

        if choice in MENU_STRUCTURE:
            select_difficulty(choice)
        else:
            print("\n >>> Ти навіть цифру правильно ввести не можеш? Спробуй ще раз.")
            time.sleep(1.5)


def select_difficulty(cat_key):
    category = MENU_STRUCTURE[cat_key]

    while True:
        clear_screen()
        print_separator()
        print(f" === {category['name']}: ОБЕРИ РІВЕНЬ СТРАЖДАНЬ ===")
        print_separator()

        for key, level_name in category['levels'].items():
            print(f" [{key}] {level_name}")

        print("\n [0] Назад")
        print_separator()

        choice = input(" Рівень >>> ")

        if choice == "0":
            return

        if choice in category['levels']:
            # Отримуємо питання для цього предмету і рівня
            questions = QUESTIONS_DB[cat_key][choice]
            show_pre_game_stats(category['levels'][choice], questions)
            return
        else:
            print("\n >>> О, Боже... Натисни 1, 2 або 3.")
            time.sleep(1)


def show_pre_game_stats(level_name, questions):
    clear_screen()
    # Фейкова статистика для залякування
    print_separator()
    print(f" ЗАВАНТАЖЕННЯ РІВНЯ: {level_name}")
    print_separator()

    time.sleep(0.5)
    print(f" [!] СТАТИСТИКА:")
    print(f"     > Виживаність: {random.randint(1, 20)}%")
    print(f"     > Середній бал гравців: 2/10")
    print(f"     > Твої шанси: 0%\n")

    input("Натисни ENTER, якщо не страшно (або закрий термінал)...")
    run_game(questions)


def run_game(questions):
    score = 0
    random.shuffle(questions)  # Перемішуємо питання

    # Беремо тільки 5 питань для гри, щоб не було довго (можна змінити)
    game_questions = questions[:5]

    for idx, q in enumerate(game_questions):
        clear_screen()
        print_separator()
        print(f" ПИТАННЯ {idx + 1}/{len(game_questions)}")
        print_separator()
        print(f"\n {q['q']}\n")

        # Перемішуємо варіанти відповідей
        options = q['opts'].copy()
        random.shuffle(options)

        # Виводимо варіанти
        for i, opt in enumerate(options):
            print(f" {i + 1}) {opt}")

        print_separator()

        # Перевірка вводу (щоб не крашилось)
        try:
            user_choice_idx = int(input(" Твоя відповідь (цифра) >>> ")) - 1
            if 0 <= user_choice_idx < len(options):
                user_ans = options[user_choice_idx]
            else:
                user_ans = "Немає такої відповіді"
        except ValueError:
            user_ans = "Це навіть не цифра"

        # Перевірка правильності
        print("\n Аналіз...")
        time.sleep(0.5)

        if user_ans == q['a']:
            print(f" ✅ ПРАВИЛЬНО. {get_insult(True)}")
            score += 1
        else:
            print(f" ❌ НЕПРАВИЛЬНО! Правильна відповідь: {q['a']}")
            print(f"    Коментар: {get_insult(False)}")

        input("\n[Enter для наступного питання]")

    # КІНЕЦЬ ГРИ
    show_result(score, len(game_questions))


def show_result(score, total):
    clear_screen()
    print_separator()
    print("       === РЕЗУЛЬТАТИ ===")
    print_separator()
    print(f"\n Твій рахунок: {score} з {total}")

    ratio = score / total

    print("\n ВЕРДИКТ СИСТЕМИ:")
    if ratio == 1.0:
        print(" 👑 НЕМОЖЛИВО! Ти зчитав коди? Або ти геній (навряд чи).")
    elif ratio > 0.7:
        print(" 😐 Ну... непогано. Як для людини.")
    elif ratio > 0.3:
        print(" 🤡 Посередність. Сіра маса.")
    else:
        print(" 💩 ПОВНИЙ ПРОВАЛ. Дошка ганьби чекає на твоє ім'я!")
